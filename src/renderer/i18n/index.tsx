export type TranslationKey = keyof typeof zh;
type TranslationValues = Record<string, string | number>;

function renderMessage(template: string, values?: TranslationValues): string {
  if (!values) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_match, key: string) => String(values[key] ?? ''));
}

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: TranslationValues) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const saved = localStorage.getItem('gta.locale');
    return saved === 'en-US' ? 'en-US' : 'zh-CN';
  });

  const value = useMemo<I18nValue>(() => {
    const setLocale = (next: Locale) => {
      localStorage.setItem('gta.locale', next);
      setLocaleState(next);
    };
    return {
      locale,
      setLocale,
      t: (key, values) => renderMessage(locale === 'en-US' ? en[key] : zh[key], values)
    };
  }, [locale]);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider');
  return value;
}

export function localizeError(
  error: unknown,
  locale: Locale,
  t: I18nValue['t'],
  fallback: TranslationKey
): string {
  const code =
    typeof error === 'object' && error !== null && 'code' in error
      ? String((error as { code?: unknown }).code ?? '')
      : '';
  if (locale === 'en-US') {
    const key = {
      IPC_VALIDATION_FAILED: 'common.error.validation',
      IPC_UNAUTHORIZED: 'common.error.unauthorized',
      IPC_UPSTREAM_UNAVAILABLE: 'common.error.upstream',
      IPC_INTERNAL: 'common.error.internal'
    }[code] as TranslationKey | undefined;
    if (key) return t(key);
    const message = error instanceof Error ? error.message : '';
    return message && !/[\u3400-\u9fff]/u.test(message) ? message : t(fallback);
  }
  return error instanceof Error ? error.message : t(fallback);
}
